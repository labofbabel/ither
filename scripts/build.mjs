// Build the runtime-neutral, single-file Ither distribution.
//
// This script intentionally runs under Node (the development runtime for this
// repository). The generated ESM bundle has no runtime-specific imports or
// package dependencies.

import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, stat } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build as esbuild } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'src', 'index.js');
const outfile = join(root, 'dist', 'ither.min.js');
const packageJson = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));

const context = {};

const stages = [
   ['bundle', async () => {
      await mkdir(dirname(outfile), { recursive: true });
      context.result = await esbuild({
         absWorkingDir: root,
         entryPoints: [entry],
         outfile,
         bundle: true,
         platform: 'neutral',
         format: 'esm',
         target: 'es2022',
         minify: true,
         treeShaking: true,
         keepNames: true,
         sourcemap: false,
         legalComments: 'none',
         charset: 'utf8',
         metafile: true,
         banner: {
            js: `/*! Ither v${packageJson.version} | generated by npm run build; do not edit. */`,
         },
         logLevel: 'warning',
      });
   }],
   ['smoke', async () => {
      const outputs = Object.entries(context.result.metafile.outputs);
      assert.equal(outputs.length, 1, `expected one build output, got ${outputs.length}`);

      const [, output] = outputs[0];
      assert.deepEqual(output.imports, [], 'bundle must not retain external imports');

      const source = await import(pathToFileURL(entry).href);
      const bytes = await readFile(outfile);
      const sha256 = createHash('sha256').update(bytes).digest('hex');
      const bundled = await import(`${pathToFileURL(outfile).href}?sha256=${sha256}`);

      assert.equal(source.Ither.version, packageJson.version, 'source Ither.version must match package.json');
      assert.equal(bundled.Ither.version, packageJson.version, 'bundle Ither.version must match package.json');

      assert.deepEqual(
         Object.keys(bundled).sort(),
         Object.keys(source).sort(),
         'bundle exports must match src/index.js',
      );

      const space = bundled.Ither.from({
         layers: {
            point: { type: 'NUM', domains: { x: { min: 0, max: 1, steps: 4 } } },
         },
      });
      assert.deepEqual(space.encode(space.decode([2n])), [2n], 'bundle must round-trip a coordinate');

      const { size } = await stat(outfile);
      context.artifact = { size, sha256 };
   }],
];

for (const [name, run] of stages) {
   process.stdout.write(`build: ${name} ... `);
   await run();
   console.log('ok');
}

console.log(`build: wrote ${relative(root, outfile)} (${context.artifact.size} bytes)`);
console.log(`build: sha256 ${context.artifact.sha256}`);
